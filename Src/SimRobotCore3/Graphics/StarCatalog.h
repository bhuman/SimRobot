  /** A star of the catalog. */
  struct Star
  {
    const char* name; /**< The name. */
    int rightAscensionHours, rightAscensionMinutes; /**< The right ascension. */
    int declinationSign, declinationDegrees, declinationMinutes; /**< The declination (the sign is separate, so that -0 degrees can be expressed). */
    float magnitude; /**< The apparent magnitude (lower is brighter). */
    float colorIndex; /**< The color index B-V (lower is bluer). */

    /** The direction to the star in the frame of the equator: the x axis points to the vernal equinox and the z axis to the pole. */
    void direction(double& x, double& y, double& z) const
    {
      constexpr double pi = 3.14159265358979323846;
      const double rightAscension = (rightAscensionHours + rightAscensionMinutes / 60.0) * (pi / 12.0);
      const double declination = declinationSign * (declinationDegrees + declinationMinutes / 60.0) * (pi / 180.0);
      x = std::cos(declination) * std::cos(rightAscension);
      y = std::cos(declination) * std::sin(rightAscension);
      z = std::sin(declination);
    }
  };

